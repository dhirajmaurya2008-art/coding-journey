// Variables, comments, datatypes in c++
#include <iostream>
using namespace std;

int main()
{
    //single line Comment
    /*Multiple line
      Comments*/

    int a = 6;
    float b = 3.4;
    char c = 'x';
    double d = 3332.2444212123;
    long e = 73628163;
    
    cout << "Integer=" << a << "\n";
    cout << "Floating-Point=" << b << "\n";
    cout << "Character=" << c << "\n";
    cout << "Floating-Point(8bytes)Double=" << d << endl;
    cout << "Integer(8bytes)Long=" << e;

    return 0;
}